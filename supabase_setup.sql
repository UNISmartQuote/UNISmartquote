CREATE SCHEMA IF NOT EXISTS unismartquote AUTHORIZATION postgres;

CREATE TABLE IF NOT EXISTS unismartquote.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    display_name TEXT NOT NULL,
    password_salt BYTEA NOT NULL,
    password_hash BYTEA NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'sales')),
    active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    must_change_password SMALLINT NOT NULL DEFAULT 0
        CHECK (must_change_password IN (0, 1)),
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until DOUBLE PRECISION,
    created_at TEXT NOT NULL DEFAULT
        TO_CHAR(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci_unique
    ON unismartquote.users (LOWER(username));

CREATE TABLE IF NOT EXISTS unismartquote.quotes (
    id TEXT PRIMARY KEY,
    owner_id BIGINT NOT NULL
        REFERENCES unismartquote.users(id) ON DELETE CASCADE,
    quote_number TEXT NOT NULL,
    customer TEXT NOT NULL,
    updated_at TEXT NOT NULL DEFAULT
        TO_CHAR(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
    payload TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS unismartquote.app_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TEXT NOT NULL DEFAULT
        TO_CHAR(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX IF NOT EXISTS quotes_owner_updated
    ON unismartquote.quotes (owner_id, updated_at DESC);

ALTER TABLE unismartquote.quotes ENABLE ROW LEVEL SECURITY;
ALTER TABLE unismartquote.quotes FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS quote_owner_isolation ON unismartquote.quotes;
CREATE POLICY quote_owner_isolation ON unismartquote.quotes
    USING (
        owner_id = NULLIF(
            CURRENT_SETTING('app.current_user_id', TRUE), ''
        )::BIGINT
    )
    WITH CHECK (
        owner_id = NULLIF(
            CURRENT_SETTING('app.current_user_id', TRUE), ''
        )::BIGINT
    );

GRANT USAGE ON SCHEMA unismartquote TO unisq_app;
GRANT SELECT, INSERT, UPDATE, DELETE
    ON ALL TABLES IN SCHEMA unismartquote TO unisq_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA unismartquote TO unisq_app;
